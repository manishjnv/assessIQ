#!/usr/bin/env node
// Z-108c: regenerate docs/plans/README.md from the front matter (first 15 lines) of docs/plans/*.md.
// Front matter = "Status: <text>" and "Rows: <ids>" lines (bold markers accepted).
// Usage: node tools/docs-plans-index.mjs [--root <dir>] [--check]
// --check exits 1 when the file would change and writes nothing.
import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const a = process.argv.slice(2);
const root = resolve(a.includes("--root") ? a[a.indexOf("--root") + 1] : join(dirname(fileURLToPath(import.meta.url)), ".."));
const dir = join(root, "docs", "plans");
const out = join(dir, "README.md");

const cell = (s, max = 140) => {
  s = (s ?? "").replace(/\|/g, "\|").trim();
  return s.length > max ? `${s.slice(0, max - 3)}...` : s;
};
// Untracked files (local reports) stay out of the index; with no git or no tracked files, list every file.
const tracked = (d) => { try { const o = execFileSync("git", ["-C", d, "ls-files", "--", "."], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).split("\n").filter(Boolean); return o.length ? new Set(o.map((x) => x.split("/")[0])) : null; } catch { return null; } };
const mds = (d) => { if (!existsSync(d)) return []; const t = tracked(d); return readdirSync(d).filter((f) => f.endsWith(".md") && f !== "README.md" && (!t || t.has(f))).sort(); };
const info = (p) => {
  const lines = readFileSync(p, "utf8").split(/\r?\n/);
  const title = (lines.find((l) => /^# /.test(l)) ?? "").replace(/^# /, "");
  const head = lines.slice(0, 15);
  const grab = (k) => head.map((l) => new RegExp(String.raw`^\s*\**${k}:\**\s*(.+)`, "i").exec(l)?.[1]).find(Boolean);
  return { title, status: grab("Status"), rows: grab("Rows") };
};

const open = mds(dir).map((f) => ({ f, ...info(join(dir, f)) }));
const arch = mds(join(dir, "archive")).map((f) => ({ f, ...info(join(dir, "archive", f)) }));
const body = [
  "<!-- GENERATED by tools/docs-plans-index.mjs. Do not edit by hand. -->",
  "# Plans index",
  "",
  "*Type: reference*",
  "",
  "One row per plan. Status and Rows come from the first 15 lines of each plan. `docs/ROADMAP.md` lists the open work.",
  "",
  "## Open or referenced",
  "",
  "| File | Title | Status | Rows |",
  "| --- | --- | --- | --- |",
  ...open.map((p) => `| [${p.f}](${p.f}) | ${cell(p.title, 100)} | ${cell(p.status) || "none"} | ${cell(p.rows) || "none"} |`),
  "",
  "## Archive (closed)",
  "",
  "| File | Title |",
  "| --- | --- |",
  ...arch.map((p) => `| [${p.f}](archive/${p.f}) | ${cell(p.title, 100)} |`),
  "",
].join("\n");

const old = existsSync(out) ? readFileSync(out, "utf8") : "";
const eol = old.includes("\r\n") ? "\r\n" : "\n";
const next = body.replace(/\n/g, eol);
if (next === old) console.log("docs-plans-index: up to date");
else if (a.includes("--check")) {
  console.error("docs-plans-index: docs/plans/README.md is out of date. Run node tools/docs-plans-index.mjs");
  process.exit(1);
} else {
  writeFileSync(out, next);
  console.log(`docs-plans-index: wrote ${open.length} open and ${arch.length} archive rows`);
}
