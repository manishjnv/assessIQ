// @vitest-environment node
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { beforeEach, describe, expect, it } from "vitest";

const tools = join(__dirname, "..");
let root: string;
const run = (script: string, ...args: string[]) =>
  spawnSync("node", [join(tools, script), ...args, "--root", root], { encoding: "utf8", cwd: root, env: { ...process.env, VITEST: "" } });
const put = (p: string, s: string) => {
  mkdirSync(join(root, p, ".."), { recursive: true });
  writeFileSync(join(root, p), s);
};
const get = (p: string) => readFileSync(join(root, p), "utf8");

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "close-session-"));
  put("docs/plans/B_plan.md", "# B plan\n\nStatus: DONE 2026-10-01\nRows: Z-2, Z-3\n");
  put("docs/plans/A_plan.md", "# A plan\n\n**Status:** open | pipe\n**Rows:** Z-1\n");
  put("docs/plans/C_plan.md", "# C plan\n\nNo front matter here.\n");
  put("docs/plans/archive/old.md", "# Old plan\n");
  put("docs/plans/README.md", "ignored\n");
});

describe("docs-plans-index", () => {
  it("generates sorted tables, with bold variant and archive", () => {
    expect(run("docs-plans-index.mjs").status).toBe(0);
    const t = get("docs/plans/README.md");
    expect(t.startsWith("<!-- GENERATED by tools/docs-plans-index.mjs. Do not edit by hand. -->\n# Plans index\n\n*Type: reference*")).toBe(true);
    expect(t).toContain("| [A_plan.md](A_plan.md) | A plan | open \| pipe | Z-1 |");
    expect(t).toContain("| [B_plan.md](B_plan.md) | B plan | DONE 2026-10-01 | Z-2, Z-3 |");
    expect(t).toContain("| [C_plan.md](C_plan.md) | C plan | none | none |");
    expect(t.indexOf("A_plan")).toBeLessThan(t.indexOf("B_plan"));
    expect(t).toContain("| [old.md](archive/old.md) | Old plan |");
    expect(t).not.toContain("README.md](");
  });

  it("--check exits 1 when stale, 0 when current, and writes nothing", () => {
    expect(run("docs-plans-index.mjs", "--check").status).toBe(1);
    expect(get("docs/plans/README.md")).toBe("ignored\n");
    run("docs-plans-index.mjs");
    expect(run("docs-plans-index.mjs", "--check").status).toBe(0);
  });
});

describe("close-session", () => {
  it("--dry-run lists 9 steps and writes nothing", () => {
    put("docs/.session-decisions.txt", "2026-10-21 | do x | S1\n");
    const r = run("close-session.mjs", "--dry-run");
    expect(r.status).toBe(0);
    expect(r.stdout.match(/^\d\. /gm)).toHaveLength(9);
    expect(existsSync(join(root, "docs/DECISIONS.md"))).toBe(false);
    expect(readdirSync(join(root, "docs/plans")).sort()).toEqual(["A_plan.md", "B_plan.md", "C_plan.md", "README.md", "archive"]);
  });

  it("decisions step is idempotent (run twice, no duplicates)", () => {
    put("docs/.session-decisions.txt", "2026-10-21 | do x | S1\n2026-10-21 | do y | S1\n2026-10-21 | do x | S1\n");
    // other steps may FAIL in the fixture; only the decisions step matters here
    run("close-session.mjs");
    const first = get("docs/DECISIONS.md");
    run("close-session.mjs");
    expect(get("docs/DECISIONS.md")).toBe(first);
    expect(first).toContain("# Decisions\n\n*Type: reference*\n\n| Date | Decision | Source |");
    expect(first.match(/\| do x \|/g)).toHaveLength(1);
    expect(first.match(/\| do y \|/g)).toHaveLength(1);
  });
});
